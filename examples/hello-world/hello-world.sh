# Dasturni ishga tushirish uchun kodni `hello-world.go`
# fayliga joylashtiring va `go run` dan foydalaning.
$ go run hello-world.go
hello world

# Ba'zan dasturlarimizni binar fayllarga kompilyatsiya
# qilmoqchi bo'lamiz. Buni `go build` yordamida qilamiz.
$ go build hello-world.go
$ ls
hello-world	hello-world.go

# So'ngra qurilgan binar faylni to'g'ridan-to'g'ri ishga tushiramiz.
$ ./hello-world
hello world

# Endi oddiy Go dasturlarini ishga tushira va qura olamiz,
# keling, til haqida ko'proq o'rganamiz.
